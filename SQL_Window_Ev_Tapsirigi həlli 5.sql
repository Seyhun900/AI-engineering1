TASK 1

SELECT FIRST_NAME, SALARY,
MIN(SALARY) OVER () AS EN_ASAGI,
ROUND (SALARY/MIN (SALARY) OVER(), 1) AS NECE_DEFE
FROM HR.EMPLOYEES
ORDER BY SALARY DESC;

TASK 2

SELECT FIRST_NAME, JOB_ID, SALARY,
AVG (SALARY) OVER(PARTITION BY JOB_ID) AS VEZIFE_ORTASI
FROM HR.EMPLOYEES
ORDER BY JOB_ID;

TASK 3

SELECT FIRST_NAME, SALARY,
RANK() OVER(ORDER BY SALARY DESC) AS RANK_YER,
DENSE_RANK () OVER (ORDER BY SALARY DESC) AS DENSE_YER
FROM HR.EMPLOYEES;

TASK 4

SELECT * 
FROM (SELECT FIRST_NAME, MANAGER_ID,
COUNT (*) OVER (PARTITION BY MANAGER_ID)AS KOMANDA_SAYI,
ROUND (AVG (SALARY) OVER (PARTITION BY MANAGER_ID)) AS KOMANDA_ORTASI
FROM HR.EMPLOYEES)
WHERE KOMANDA_SAYI > 6

TASK 5

SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
MAX (SALARY) OVER (PARTITION BY DEPARTMENT_ID) AS SOBE_MAX,
CASE WHEN SALARY = MAX(SALARY) OVER (PARTITION BY DEPARTMENT_ID) 
THEN 'LIDER' ELSE '-'
END AS STATUS
FROM HR.EMPLOYEES;

TASK 6

SELECT FIRST_NAME, JOB_ID, SALARY, YER
FROM (SELECT FIRST_NAME, JOB_ID, SALARY,
DENSE_RANK () OVER (PARTITION BY JOB_ID ORDER BY SALARY DESC) AS YER
FROM HR.EMPLOYEES)
WHERE JOB_ID='SA_REP' AND YER <= 3

TASK 7

SELECT JOB_ID, COUNT(*) AS ISCI_SAYI, AVG (SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING AVG (SALARY) > 10000


SELECT DISTINCT JOB_ID, ISCI_SAYI, ORTA_MAAS
FROM (SELECT JOB_ID, COUNT (*) OVER (PARTITION BY JOB_ID) AS ISCI_SAYI,
AVG(SALARY) OVER (PARTITION BY JOB_ID) AS ORTA_MAAS
FROM HR.EMPLOYEES)
WHERE ORTA_MAAS > 10000;

TASK 8

SELECT FIRST_NAME, DEPARTMENT_ID, SALARY, YER
FROM ( SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
DENSE_RANK () OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS YER
FROM HR.EMPLOYEES)
WHERE YER <= 2;

TASK 9

SELECT FIRST_NAME, DEPARTMENT_ID, SALARY
FROM (SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
DENSE_RANK () OVER (PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS YER
FROM HR.EMPLOYEES)
WHERE YER = 2

TASK 10

SELECT DISTINCT DEPARTMENT_ID,
ROUND(AVG (SALARY) OVER (PARTITION BY DEPARTMENT_ID)) AS SOBE_ORTASI,
ROUND(AVG (SALARY) OVER()) AS SIRKET_ORTASI,
CASE WHEN AVG (SALARY) OVER (PARTITION BY DEPARTMENT_ID) > AVG (SALARY) OVER() THEN 'YUXARI' ELSE 'ASAGI'
END AS VEZIYYET
FROM HR.EMPLOYEES;

