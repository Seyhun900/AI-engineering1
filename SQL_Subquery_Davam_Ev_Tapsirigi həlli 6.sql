TASK 1

SELECT JOB_TITLE, MAX_SALARY
FROM HR.JOBS
WHERE MAX_SALARY>(SELECT AVG(MAX_SALARY) FROM HR.JOBS)

TASK 2

SELECT FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID FROM HR.EMPLOYEES 
WHERE FIRST_NAME='Steven' AND LAST_NAME='King')
AND NOT (first_name = 'Steven' AND last_name = 'King');

TASK 3

SELECT FIRST_NAME, LAST_NAME, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID IN (SELECT JOB_ID FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING COUNT(*)=1)

TASK 4

SELECT DEPARTMENT_ID, 
COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) > (SELECT COUNT(*)FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID 
FROM HR.DEPARTMENTS 
WHERE DEPARTMENT_NAME = 'IT'))
ORDER BY 
ISCI_SAYI DESC;

TASK 5

SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
SELECT DEPARTMENT_ID FROM HR.DEPARTMENTS WHERE LOCATION_ID IN (
SELECT LOCATION_ID FROM HR.LOCATIONS WHERE COUNTRY_ID = (
SELECT COUNTRY_ID FROM HR.COUNTRIES 
WHERE COUNTRY_NAME = 'United Kingdom of Great Britain and Northern Ireland')))

TASK 6

SELECT JOB_TITLE, MIN_SALARY, MAX_SALARY
FROM HR.JOBS
WHERE JOB_ID IN(
SELECT JOB_ID
FROM HR.EMPLOYEES
GROUP BY JOB_ID 
HAVING COUNT(*)>= ALL (SELECT COUNT(*)
FROM HR.EMPLOYEES GROUP BY JOB_ID))

TASK 7

SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_ID, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
SELECT DEPARTMENT_ID 
FROM HR.DEPARTMENTS 
WHERE DEPARTMENT_NAME IN ('Finance', 'Accounting'))
AND SALARY = (
SELECT MAX(SALARY)
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (
SELECT DEPARTMENT_ID FROM HR.DEPARTMENTS 
WHERE DEPARTMENT_NAME IN ('Finance', 'Accounting')));

TASK 8

SELECT DEPARTMENT_ID, ROUND(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES
WHERE AVG(SALARY) > (SELECT AVG(SALARY)
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = (SELECT DEPARTMENT_ID
FROM HR.DEPARTMENTS
WHERE DEPARTMENT_NAME = 'it'
ORDER BY DEPARTMENT_ID))
GROUP BY DEPARTMENT_ID
ORDER BY ORTA_MAAS DESC;

TASK 9

SELECT CITY, COUNTRY_ID
FROM HR.LOCATIONS
WHERE LOCATION_ID IN (
SELECT LOCATION_ID
FROM HR.DEPARTMENTS
WHERE DEPARTMENT_ID IN (
SELECT DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) >= ALL (
SELECT COUNT(*)
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID )));

TASK 10

SELECT J.JOB_TITLE,E.ISCI_SAYI
FROM HR.JOBS J
JOIN (SELECT JOB_ID,COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE JOB_ID IS NOT NULL
GROUP BY JOB_ID) E
ON J.JOB_ID = E.JOB_ID
WHERE E.ISCI_SAYI > (
SELECT AVG(SAY)FROM (SELECT COUNT(*) AS SAY
FROM HR.EMPLOYEES
WHERE JOB_ID IS NOT NULL
GROUP BY JOB_ID))
ORDER BY E.ISCI_SAYI DESC;

